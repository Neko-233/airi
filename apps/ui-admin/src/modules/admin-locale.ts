const locale = shallowRef<AdminLocale>(initialLocale())

/**
 * Resolves the initial admin locale from local storage with Chinese as the default.
 */
function initialLocale(): AdminLocale {
  if (typeof localStorage === 'undefined' || typeof localStorage.getItem !== 'function')
    return 'zh-CN'

  const stored = localStorage.getItem(STORAGE_KEY)
  return stored === 'en-US' || stored === 'zh-CN' ? stored : 'zh-CN'
}

/**
 * Replaces named placeholders inside translated messages.
 */
function interpolate(message: string, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    message,
  )
}

/**
 * Reads a translated admin UI message for the current locale.
 */
export function t(key: string, values?: Record<string, string | number>): string {
  return interpolate(messages[locale.value][key] ?? messages['en-US'][key] ?? key, values)
}

/**
 * Persists and activates the selected admin locale.
 */
export function setAdminLocale(nextLocale: AdminLocale) {
  locale.value = nextLocale
  if (typeof localStorage !== 'undefined' && typeof localStorage.setItem === 'function')
    localStorage.setItem(STORAGE_KEY, nextLocale)
}

/**
 * Formats numbers with the active admin locale.
 */
export function formatAdminNumber(value: number | null | undefined): string {
  return new Intl.NumberFormat(locale.value).format(value ?? 0)
}

/**
 * Formats dates with the active admin locale.
 */
export function formatAdminDate(value: string, options: Intl.DateTimeFormatOptions = { dateStyle: 'medium' }): string {
  return new Intl.DateTimeFormat(locale.value, options).format(new Date(value))
}

/**
 * Provides reactive locale state and helpers to Vue components.
 */
export function useAdminLocale() {
  const nextLocaleLabel = computed(() => locale.value === 'zh-CN' ? 'English' : '中文')
  const currentLocaleLabel = computed(() => locale.value === 'zh-CN' ? '中文' : 'English')

  /**
   * Switches between Chinese and English admin UI labels.
   */
  function toggleLocale() {
    setAdminLocale(locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
  }

  return {
    currentLocaleLabel,
    locale,
    nextLocaleLabel,
    t,
    toggleLocale,
  }
}
